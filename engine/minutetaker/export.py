def to_markdown(meeting: dict, minutes: Optional[dict], summaries: dict, segments: list[dict],
                include_transcript: bool = True, include_summary: bool = True) -> str:
    m = minutes or {}
    L = labels(m.get("language") or meeting.get("language"))
    date, time = _dt(meeting)
    out = [f"# {m.get('title') or meeting.get('title')}", "",
           f"**{L['date']}:** {date} {time} · **{L['duration']}:** {fmt_duration(meeting.get('duration_s'))} · "
           f"**{L['platform']}:** {meeting.get('platform')}", ""]
    if include_summary:
        if m.get("tldr"):
            out += [f"## {L['tldr']}", *[f"- {t}" for t in m["tldr"]], ""]
        if m.get("executive_summary"):
            out += [f"## {L['exec']}", m["executive_summary"], ""]
    if minutes:
        out += [f"## {L['attendees']}", *[f"- {a['name']}" + (f" — {a['role']}" if a.get("role") else "")
                                          for a in m.get("attendees", [])], ""]
        if m.get("agenda"):
            out += [f"## {L['agenda']}", *[f"{i + 1}. {a}" for i, a in enumerate(m["agenda"])], ""]
        out += [f"## {L['discussion']}"]
        for d in m.get("discussion", []):
            out += [f"### {d['topic']}", *[f"- {p}" for p in d.get("points", [])], ""]
        out += [f"## {L['decisions']}", *[f"- **D{i + 1}** {d}" for i, d in enumerate(m.get("decisions", []))], ""]
        out += [f"## {L['actions']}", f"| # | {L['task']} | {L['owner']} | {L['due']} |", "|---|---|---|---|",
                *[f"| A{i + 1} | {a['task']} | {a.get('owner', '')} | {a.get('due', '')} |"
                  for i, a in enumerate(m.get("action_items", []))], ""]
        out += [f"## {L['issues']}", *[f"- {x}" for x in m.get("open_issues", [])], ""]
        if m.get("next_meeting"):
            out += [f"## {L['next']}", m["next_meeting"], ""]
    if include_transcript and segments:
        out += [f"## {L['transcript']}", *[f"`[{fmt_ts(s['start_s'])}]` **{s.get('speaker')}:** {s['text']}"
                                          for s in segments]]
    return "\n".join(out) + "\n"


def to_txt(segments: list[dict]) -> str:
    return "\n".join(f"[{fmt_ts(s['start_s'])}] {s.get('speaker')}: {s['text']}" for s in segments) + "\n"


def _srt_ts(t: float) -> str:
    ms = int(round(t * 1000))
    return f"{ms // 3600000:02d}:{ms % 3600000 // 60000:02d}:{ms % 60000 // 1000:02d},{ms % 1000:03d}"


def to_srt(segments: list[dict]) -> str:
    return "\n".join(f"{i + 1}\n{_srt_ts(s['start_s'])} --> {_srt_ts(s['end_s'])}\n{s.get('speaker')}: {s['text']}\n"
                     for i, s in enumerate(segments))


def soffice() -> Optional[str]:
    for name in ("soffice", "libreoffice"):
        p = shutil.which(name)
        if p:
            return p
    for p in (r"C:\Program Files\LibreOffice\program\soffice.exe",
              "/Applications/LibreOffice.app/Contents/MacOS/soffice"):
        if Path(p).exists():
            return p
    return None


def docx_to_pdf(docx_path: Path) -> Path:
    exe = soffice()
    if not exe:
        raise RuntimeError("PDF export needs LibreOffice installed (or open the .docx in Word and Save as PDF)")
    subprocess.run([exe, "--headless", "--convert-to", "pdf", "--outdir", str(docx_path.parent), str(docx_path)],
                   check=True, capture_output=True, timeout=180)
    pdf = docx_path.with_suffix(".pdf")
    if not pdf.exists():
        raise RuntimeError("PDF conversion failed")
    return pdf
